#!/usr/bin/env python3
"""Tables of the evaluation. Usage: python3 -I scripts/analyze.py [repo_root]
Reads cases.tsv and transcripts/, writes results.tsv (one row per answer), results.md (tables) and,
if it does not exist, manual_review_sample.tsv. Makes no model calls."""
import csv, math, os, random, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common
E = common.root(sys.argv)

def wilson(k, n, z=1.96):
    if n == 0: return (float('nan'),) * 3
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0, c - h), min(1, c + h)
def fmt(k, n):
    if n == 0: return '—'
    p, lo, hi = wilson(k, n); return f'{k}/{n} ({100*p:.0f}%; {100*lo:.0f}–{100*hi:.0f})'
def mcnemar(b, c):  # exact, two-sided
    n = b + c
    if n == 0: return 1.0
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(0, min(b, c) + 1)) / 2 ** n)

def serious(expected, answer):
    if expected in ('AVOID', 'ADJUST') and answer == 'NORMAL': return True
    if expected == 'NORMAL' and answer in ('AVOID', 'ADJUST'): return True
    return False

JUDGE_FIELDS = ('answer_action', 'action_correct', 'guideline_cited', 'citation_correct', 'citation_suspect',
                'states_no_record', 'abstains')
rows = []
for m, arm, c in common.cells(E):
    t = common.read_transcript(E, m, arm, c['id'])
    if t is None: continue   # cell not run (e.g. arm C skipped)
    j = t['judge'] if t['answered'] else None
    row = dict(model=m, model_id=t['model_id'] or '', arm=arm, id=c['id'], covered=c['covered_by_deepdna'], genes=c['genes'],
               drug=c['drug'], expected=c['expected_category'], answered=int(t['answered']), graded=int(j is not None),
               n_tool_calls=len(t['tool_calls']), tools_called=','.join(sorted({x['name'] for x in t['tool_calls']})),
               web_search_requests=t['web_search_requests'])
    for k in JUDGE_FIELDS: row[k] = (j or {}).get(k, '')
    row['judge_note_es'] = (j or {}).get('note_es', '')
    row['serious_error'] = int(serious(c['expected_category'], j.get('answer_action'))) if j else ''
    rows.append(row)
with open(E + '/results.tsv', 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]), delimiter='\t', lineterminator='\n'); w.writeheader(); w.writerows(rows)

T = lambda v: v is True
out = ['# Results (generated by scripts/analyze.py; do not edit by hand)', '']
ev = [r for r in rows if r['graded']]
out.append(f"Answers expected: {len(rows)} · answered: {sum(r['answered'] for r in rows)} · graded by the judge: {len(ev)}")
out.append('Model ids: ' + ', '.join(f"{m} = {'/'.join(sorted({r['model_id'] for r in rows if r['model']==m and r['model_id']}))}" for m in common.MODELS))
out.append('')
out.append('Arms: A no tools · B DeepDNA MCP server only · C web search only. The judge notes are in Spanish, as the judge wrote them.')
out.append('')
def table(title, keep):
    out.append(f'## {title}'); out.append('')
    out.append('| Model | Arm | n | Correct action (95% Wilson CI) | Serious errors | No answer | CPIC/DPWG citation correct | Citation suspect | Used the tool |')
    out.append('|---|---|---|---|---|---|---|---|---|')
    for m in common.MODELS:
        for arm in common.ARMS:
            rs = [r for r in ev if r['model'] == m and r['arm'] == arm and keep(r)]
            if not rs: continue
            n = len(rs); ng = [r for r in rs if r['expected'] != 'OTHER']
            out.append(f"| {m} | {arm} | {n} | {fmt(sum(T(r['action_correct']) for r in rs), n)} | {sum(r['serious_error'] for r in ng)}/{len(ng)} | "
                       f"{sum(r['answer_action']=='NO_ANSWER' for r in rs)} | {fmt(sum(T(r['citation_correct']) for r in rs), n)} | "
                       f"{sum(T(r['citation_suspect']) for r in rs)} | {'—' if arm=='A' else str(sum(r['n_tool_calls']>0 for r in rs))+'/'+str(n)} |")
    out.append('')
table('Cases DeepDNA covers', lambda r: r['covered'] == 'yes')
table('Cases DeepDNA does NOT cover', lambda r: r['covered'] == 'no')
table('All cases', lambda r: True)

out.append('## Uncovered cases: does the answer acknowledge it? (according to the judge)'); out.append('')
out.append('| Model | Arm | n | States there is no record | Abstains | Correct action |'); out.append('|---|---|---|---|---|---|')
for m in common.MODELS:
    for arm in common.ARMS:
        rs = [r for r in ev if r['model'] == m and r['arm'] == arm and r['covered'] == 'no']
        if rs: out.append(f"| {m} | {arm} | {len(rs)} | {sum(T(r['states_no_record']) for r in rs)} | {sum(T(r['abstains']) for r in rs)} | {sum(T(r['action_correct']) for r in rs)} |")
out.append('')

out.append('## Paired comparison (same cases; exact two-sided McNemar)'); out.append('')
out.append('| Model | Cases | Comparison | Pairs | Only the 1st correct | Only the 2nd correct | p |'); out.append('|---|---|---|---|---|---|---|')
idx = {(r['model'], r['arm'], r['id']): r for r in ev}
for m in common.MODELS:
    for cov, name in (('yes', 'covered'), ('no', 'uncovered'), (None, 'all')):
        for x, y in (('A', 'B'), ('A', 'C'), ('C', 'B')):
            ids = [i for (mm, arm, i), r in idx.items() if mm == m and arm == x and (m, y, i) in idx and (cov is None or r['covered'] == cov)]
            if not ids: continue
            b = sum(T(idx[m, x, i]['action_correct']) and not T(idx[m, y, i]['action_correct']) for i in ids)
            c = sum(T(idx[m, y, i]['action_correct']) and not T(idx[m, x, i]['action_correct']) for i in ids)
            out.append(f'| {m} | {name} | {x} vs {y} | {len(ids)} | {b} | {c} | {mcnemar(b, c):.3f} |')
out.append('')

out.append('## Serious errors, one by one'); out.append('')
for r in ev:
    if r['serious_error']: out.append(f"- {r['model']}/{r['arm']}/{r['id']} ({r['genes']} · {r['drug']}; covered: {r['covered']}): expected {r['expected']}, answer {r['answer_action']}. Judge note: {r['judge_note_es']}")
out.append('')
out.append('## By expected category (covered cases, correct action)'); out.append('')
out.append('| Model | Arm | AVOID | ADJUST | NORMAL | OTHER |'); out.append('|---|---|---|---|---|---|')
for m in common.MODELS:
    for arm in common.ARMS:
        rs = [r for r in ev if r['model'] == m and r['arm'] == arm and r['covered'] == 'yes']
        if rs: out.append(f'| {m} | {arm} | ' + ' | '.join(f"{sum(T(r['action_correct']) for r in rs if r['expected']==k)}/{sum(r['expected']==k for r in rs)}" for k in ('AVOID', 'ADJUST', 'NORMAL', 'OTHER')) + ' |')
out.append('')
open(E + '/results.md', 'w').write('\n'.join(out) + '\n')

# sample for the manual review: 24 answers, 8 per arm, fixed seed, drawn without the judge's grade
if not os.path.exists(E + '/manual_review_sample.tsv'):
    rng = random.Random(20261115)
    with open(E + '/manual_review_sample.tsv', 'w', newline='') as f:
        w = csv.writer(f, delimiter='\t', lineterminator='\n'); w.writerow(['key', 'model', 'arm', 'id'])
        for arm in common.ARMS:
            rs = [r for r in rows if r['arm'] == arm and r['answered']]
            for i, r in enumerate(rng.sample(rs, min(8, len(rs)))): w.writerow([f'{arm}{i}', r['model'], arm, r['id']])

# agreement between the automatic judge and the manual review
if os.path.exists(E + '/manual_review.tsv'):
    man = list(csv.DictReader(open(E + '/manual_review.tsv'), delimiter='\t'))
    a = ['', '## Agreement between the automatic judge and the manual review', '', f'Answers reviewed by hand: {len(man)}', '',
         '| Field | Agreement |', '|---|---|']; dis = []
    for field in ('answer_action', 'action_correct', 'citation_correct'):
        k = 0
        for x in man:
            r = idx[x['model'], x['arm'], x['id']]
            auto = r[field] if field == 'answer_action' else ('yes' if T(r[field]) else 'no')
            if auto == x[field]: k += 1
            else: dis.append(f"- {x['model']}/{x['arm']}/{x['id']} · {field}: judge = {auto}, manual = {x[field]}. {x.get('comment','')}")
        a.append(f'| {field} | {fmt(k, len(man))} |')
    a += ['', 'Disagreements:', ''] + (dis or ['- none'])
    open(E + '/results.md', 'a').write('\n'.join(a) + '\n')
print(open(E + '/results.md').read())
